    #[test]
    fn message_structs_round_trip() {
        let base = "//! doc\n\n// bonsai:message\n";
        let with = crate::insert_before_marker(
            Path::new(MESSAGES),
            base.to_string(),
            MESSAGE_MARKER,
            &(message_struct("Reading", &[("temp".into(), "f32".into())]) + "\n"),
        );
        assert_eq!(
            with,
            "//! doc\n\n#[derive(Clone, Debug)]\npub struct Reading {\n    pub temp: f32,\n}\n\n// bonsai:message\n"
        );
        let with_two = crate::insert_before_marker(
            Path::new(MESSAGES),
            with.clone(),
            MESSAGE_MARKER,
            &(message_struct("Beat", &[]) + "\n"),
        );
        assert_eq!(graph::parse_messages(&with_two), ["Reading", "Beat"]);
        assert_eq!(without_struct(&with_two, "Beat").unwrap(), with);
        assert_eq!(without_struct(&with, "Reading").unwrap(), base);
        assert!(without_struct(&with, "Read").is_none());
    }
