    #[test]
    fn macro_use_is_added_once() {
        let old = "//! doc\n\nmod bonsai;\nmod branches;\n";
        let new = with_macro_use(old).unwrap();
        assert_eq!(new, "//! doc\n\n#[macro_use]\nmod bonsai;\nmod branches;\n");
        assert_eq!(with_macro_use(&new), None);
        assert_eq!(with_macro_use("mod branches;\n"), None);
        assert_eq!(
            with_macro_use("mod bonsai;"),
            Some("#[macro_use]\nmod bonsai;".into())
        );
    }

    #[test]
    fn arms_match_their_variant_only() {
        assert!(is_input_arm("            Input::Beat(_beat) => {}", "Beat"));
        assert!(is_input_arm("Input::Beat(b) => {", "Beat"));
        assert!(!is_input_arm("Input::BeatTwice(b) => {}", "Beat"));
        assert!(is_input_arm("    Input::Tick => {}", "Tick"));
        assert!(is_input_arm("Input::Tick | Input::Beat(_) => {}", "Tick"));
        assert!(!is_input_arm("Input::TickTock(_) => {}", "Tick"));
        assert_eq!(
            arm("RouteFollow"),
            "Input::RouteFollow(_route_follow) => {}"
        );
        assert_eq!(arm("Beacon"), "Input::Beacon(_beacon) => {}");
        assert_eq!(arm("Tick"), "Input::Tick => {}");
    }

